def language() -> str:
    value = db.get_setting("language")
    return value if value in LANGUAGES else "en"


def translate(locale: str, message: str, **values) -> str:
    text = ENGLISH.get(message, message) if locale == "en" else message
    return text.format(**values) if values else text


def message(text: str, **values) -> str:
    return translate(current_language.get(), text, **values)
